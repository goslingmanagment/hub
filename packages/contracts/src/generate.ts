import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { createLogger } from "@agency_hub_core/shared";

import { buildApiServer, normalizeOpenApiDocument } from "../../../apps/runtime/src/api/server.ts";
import { renderAuthorizationPolicyMarkdown } from "./authorization-policy.ts";
import { buildSdkFiles, computeContractHash } from "./generate-sdk.ts";

export interface ContractArtifactDrift {
  path: string;
  reason: "missing" | "stale" | "extra";
}

export interface ContractArtifactsCheckResult {
  ok: boolean;
  checked: string[];
  drifted: ContractArtifactDrift[];
}

export async function buildExpectedContractArtifacts(): Promise<Map<string, string>> {
  const encryptionKey = Buffer.alloc(32, 0);
  const server = await buildApiServer({
    config: {
      databaseUrl: "",
      encryptionKey,
      encryptionKeyVersion: 1,
      encryptionKeysByVersion: new Map([[1, encryptionKey]]),
      logLevel: "silent",
      apiHost: "0.0.0.0",
      apiPort: 3000,
      trustProxy: false,
      isProduction: false,
      sessionTtlDays: 30,
      fanslyBaseUrl: "https://apiv3.fansly.com/api/v1",
      syncHttpTraceFile: null,
      fanslyDefaultDelayMs: 2500,
      onlyFansDefaultDelayMs: 1000,
      lakeDir: "lake",
      syncPageExecutorConcurrency: 1,
      syncObservabilityRetentionDays: 30,
      healthSyncLightMaxAgeMinutes: 180,
      healthSyncMonitoringToken: null,
      telegramBotToken: null,
      telegramChatId: null,
      telegramEnabled: false,
      telegramReportHourUtc: 9,
      serviceEgressProxyUrl: null,
      serviceEgressProxyUsername: null,
      serviceEgressProxyPassword: null,
    },
    logger: createLogger("silent"),
    pool: {} as never,
    db: {} as never,
    async close() {},
  });

  try {
    await server.ready();
    const spec = normalizeOpenApiDocument(server.swagger() as unknown as Record<string, unknown>);
    const openApiDocumentJson = `${JSON.stringify(spec, null, 2)}\n`;
    const contractHash = computeContractHash(openApiDocumentJson);
    const contractHashTs = "// Generated by `pnpm contracts:generate`. Do not edit by hand.\n\n"
      + "/** sha256 over the normalized OpenAPI document actually served by this build. */\n"
      + `export const KERNEL_CONTRACT_HASH = ${JSON.stringify(contractHash)};\n`;
    const policyMarkdown = renderAuthorizationPolicyMarkdown(server.routePolicyTable);
    const sdkFiles = buildSdkFiles({
      routePolicyTable: server.routePolicyTable,
      openApiDocumentJson,
      sdkVersion: "0.4.0",
    });

    const artifacts = new Map<string, string>([
      ["reference/agency-hub.openapi.json", openApiDocumentJson],
      ["packages/contracts/src/contract-hash.ts", contractHashTs],
      ["docs/generated/authorization-policy.md", policyMarkdown],
    ]);
    for (const [relativePath, content] of sdkFiles) {
      artifacts.set(path.posix.join("packages/sdk", relativePath.split(path.sep).join("/")), content);
    }
    return artifacts;
  } finally {
    await server.close();
  }
}

async function listGeneratedSdkFilesOnDisk(sdkDir: string, prefix = ""): Promise<string[]> {
  if (!existsSync(sdkDir)) {
    return [];
  }
  const entries = await readdir(sdkDir, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    if (entry.name === "node_modules" || entry.name === "dist" || entry.name.startsWith(".")) {
      continue;
    }
    const rel = prefix ? path.posix.join(prefix, entry.name) : entry.name;
    const fullPath = path.join(sdkDir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await listGeneratedSdkFilesOnDisk(fullPath, rel));
    } else if (entry.isFile()) {
      files.push(path.posix.join("packages/sdk", rel));
    }
  }
  return files.sort();
}

export async function checkContractArtifacts(options?: {
  rootDir?: string;
  expected?: Map<string, string>;
}): Promise<ContractArtifactsCheckResult> {
  const rootDir = path.resolve(options?.rootDir ?? process.cwd());
  const expected = options?.expected ?? await buildExpectedContractArtifacts();
  // In a full checkout (`.git` present), all four generated targets are required.
  // Inside a Docker build context (`.dockerignore` omits `.git`, `reference/`, `docs/`),
  // `packages/contracts/src/contract-hash.ts` and `packages/sdk/**` are always checked
  // (pinning the full OpenAPI sha256 + every operation), while `reference/` and `docs/`
  // are checked whenever those directories exist.
  const hasGit = existsSync(path.join(rootDir, ".git"));
  const checkReference = hasGit || existsSync(path.join(rootDir, "reference"));
  const checkDocs = hasGit || existsSync(path.join(rootDir, "docs"));

  const checked: string[] = [];
  const drifted: ContractArtifactDrift[] = [];
  const expectedSdkPaths = new Set<string>();

  for (const [relativePath, expectedContent] of expected) {
    if (relativePath === "reference/agency-hub.openapi.json" && !checkReference) {
      continue;
    }
    if (relativePath === "docs/generated/authorization-policy.md" && !checkDocs) {
      continue;
    }
    if (relativePath.startsWith("packages/sdk/")) {
      expectedSdkPaths.add(relativePath);
    }
    checked.push(relativePath);

    const target = path.join(rootDir, relativePath);
    let actualContent: string;
    try {
      actualContent = await readFile(target, "utf8");
    } catch (error) {
      if ((error as NodeJS.ErrnoException)?.code === "ENOENT") {
        drifted.push({ path: relativePath, reason: "missing" });
        continue;
      }
      throw error;
    }
    if (actualContent !== expectedContent) {
      drifted.push({ path: relativePath, reason: "stale" });
    }
  }

  for (const existingSdkPath of await listGeneratedSdkFilesOnDisk(path.join(rootDir, "packages/sdk"))) {
    if (!expectedSdkPaths.has(existingSdkPath)) {
      drifted.push({ path: existingSdkPath, reason: "extra" });
    }
  }

  return {
    ok: drifted.length === 0,
    checked,
    drifted,
  };
}

export async function writeContractArtifacts(options?: { rootDir?: string }): Promise<void> {
  const rootDir = path.resolve(options?.rootDir ?? process.cwd());
  const artifacts = await buildExpectedContractArtifacts();
  for (const [relativePath, content] of artifacts) {
    const target = path.join(rootDir, relativePath);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content, "utf8");
  }
}

function parseCliArgs(argv: readonly string[]): { check: boolean; rootDir: string } {
  let check = false;
  let rootDir = process.cwd();
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") {
      check = true;
    } else if (arg === "--root") {
      const value = argv[i + 1];
      if (!value) {
        throw new Error("--root requires a directory path");
      }
      rootDir = path.resolve(value);
      i += 1;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return { check, rootDir };
}

async function main() {
  const { check, rootDir } = parseCliArgs(process.argv.slice(2));
  if (!check) {
    await writeContractArtifacts({ rootDir });
    return;
  }

  const result = await checkContractArtifacts({ rootDir });
  if (!result.ok) {
    for (const item of result.drifted) {
      console.error(`[contracts:check] ${item.reason}: ${item.path}`);
    }
    console.error(
      "Generated contracts are stale: run `pnpm contracts:generate` and commit every file it changes or adds.",
    );
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
