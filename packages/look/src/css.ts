/**
 * The token values written out as CSS: the two copies Hub keeps (Workboard's
 * `--ui-*`, the console's `--color-*` under Tailwind's `@theme static`), and the
 * small helpers another repository needs to take the same values into its own
 * names. Pure functions over `tokens.ts`; `packages/look/generate.ts` writes the two
 * Hub copies with them, `scripts/vendor-look.mjs` ships them compiled.
 */
import {
  COLORS,
  CONSOLE_TYPE_SIZES,
  CONTROL,
  FONT,
  FOCUS,
  LAYERS,
  MOTION,
  RADIUS,
  READING,
  SHADOW,
  SPACE,
  TYPE_SCALE,
  UI_TYPE_SIZES,
  type ColorToken,
  type ThemeValue,
} from "./tokens.js";

/** `light-dark(light, dark)`, or the one value both themes share. */
export function themeValue(value: ThemeValue): string {
  return typeof value === "string" ? value : `light-dark(${value[0]}, ${value[1]})`;
}

/** One theme's side of a value. */
export function sideOf(value: ThemeValue, theme: "light" | "dark"): string {
  return typeof value === "string" ? value : value[theme === "light" ? 0 : 1];
}

/**
 * «52 70 123» for `#34467b`: the channels a closed shadow root takes
 * (`rgb(var(--x) / 0.5)`), as the extension keeps its values.
 */
export function rgbChannels(hex: string): string {
  const match = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!match) throw new Error(`rgbChannels: ${hex} is not a #rrggbb colour`);
  const value = Number.parseInt(match[1]!, 16);
  return `${(value >> 16) & 255} ${(value >> 8) & 255} ${value & 255}`;
}

const colors = Object.values(COLORS) as ColorToken[];

const GENERATED = [
  "GENERATED by `node --import tsx/esm packages/look/generate.ts` from packages/look/src/tokens.ts: do not edit here.",
  "Change a value there, run the generator, commit both copies (CI checks they are fresh).",
];

function header(lines: readonly string[]): string {
  return ["/*", ...[...GENERATED, "", ...lines].map((line) => (line === "" ? " *" : ` * ${line}`)), " */"].join("\n");
}

/** Workboard's copy (`packages/ui/src/styles/tokens.css`): every token as `--ui-*`, in `@layer ui`. */
export function renderUiTokensCss(): string {
  const lines: string[] = [];
  const add = (name: string, value: string | number) => lines.push(`    --ui-${name}: ${value};`);
  const blank = () => lines.push("");

  for (const color of colors) if (color.ui) add(color.ui, themeValue(color.value));
  blank();
  add("font", FONT.family);
  for (const size of UI_TYPE_SIZES) {
    add(`fs-${size}`, `${size}px`);
    add(`lh-${size}`, `${TYPE_SCALE[size]}px`);
  }
  add("lh-read", `${READING.lineHeight}px`);
  add("measure", READING.measure);
  blank();
  for (const [step, px] of Object.entries(SPACE)) add(`space-${step}`, `${px}px`);
  blank();
  add("radius-sm", `${RADIUS.inner}px`);
  add("radius", `${RADIUS.control}px`);
  add("radius-lg", `${RADIUS.card}px`);
  add("control-sm", `${CONTROL.sm}px`);
  add("control", `${CONTROL.md}px`);
  add("control-lg", `${CONTROL.lg}px`);
  blank();
  add("shadow-raised", SHADOW.raised);
  add("shadow-float", `${SHADOW.float}, ${SHADOW.floatRing}`);
  add("focus", `${FOCUS.width}px solid var(--ui-accent)`);
  add("focus-offset", `${FOCUS.offset}px`);
  add("fast", MOTION.fast);
  add("slide", MOTION.slide);
  blank();
  for (const [layer, z] of Object.entries(LAYERS)) add(`z-${layer}`, z);
  blank();
  lines.push("    /* How far a table's header sticks from the top: the app sets it under its own header. */");
  add("sticky-top", "0px");

  return [
    header([
      "Tokens of the shared design system (packages/ui): Workboard and the shared components.",
      "Every colour is light-dark(light, dark); `color-scheme` picks the side: the system's by",
      "default, or [data-theme=\"light\" | \"dark\"] on <html> (src/theme.ts). Everything is",
      "prefixed `--ui-`, so the console's `--color-*` and these live side by side.",
    ]),
    "@layer ui {",
    "  :root {",
    "    color-scheme: light dark;",
    "",
    ...lines,
    "  }",
    "",
    "  :root[data-theme=\"light\"] {",
    "    color-scheme: light;",
    "  }",
    "",
    "  :root[data-theme=\"dark\"] {",
    "    color-scheme: dark;",
    "  }",
    "}",
    "",
  ].join("\n");
}

/**
 * The console's copy (`apps/dashboard/src/styles/tokens.css`): the colours as
 * `--color-*` and the type scale, radii and bold weight under Tailwind's
 * `@theme static` (so its utilities and `var()` read them), the two shadows on `:root`.
 */
export function renderConsoleTokensCss(): string {
  const theme: string[] = [];
  const add = (name: string, value: string | number) => theme.push(`  --${name}: ${value};`);

  for (const color of colors) if (color.console) add(`color-${color.console}`, themeValue(color.value));
  theme.push("");
  for (const [name, size] of Object.entries(CONSOLE_TYPE_SIZES)) {
    add(`text-${name}`, `${size}px`);
    add(`text-${name}--line-height`, `${TYPE_SCALE[size]}px`);
  }
  add("font-weight-bold", FONT.weightBold);
  theme.push("");
  add("radius-card", `${RADIUS.card}px`);
  add("radius-button", `${RADIUS.control}px`);
  add("radius-inner", `${RADIUS.inner}px`);

  return [
    header([
      "The console's tokens: imported first by apps/dashboard/src/globals.css. The names stay",
      "`--color-*`, `--text-*`, `--radius-*`, so Tailwind and `var()` read them as before.",
      "Below 13 px there is nothing; 13 px is axes, heat maps and .kbd only.",
    ]),
    "@theme static {",
    ...theme,
    "}",
    "",
    ":root {",
    `  --shadow-raised: ${SHADOW.raised};`,
    `  --shadow-float: ${SHADOW.float};`,
    "}",
    "",
  ].join("\n");
}
